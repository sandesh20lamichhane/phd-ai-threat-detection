"""Develop the Level 1-2 candidates on CICIDS2017 train + val, then freeze (amendment 1.4, ADR-0007).

    python scripts/develop.py --space cic --candidate random_forest   # one candidate, resumes if interrupted
    python scripts/develop.py --all                                    # every candidate in every feature space
    python scripts/develop.py --status                                 # progress table
    python scripts/develop.py --freeze                                 # pick the proposed detector, seal models
    python scripts/develop.py --lanl --candidate xgboost               # Level 3 (LANL days 1-13 only), resumable
    python scripts/develop.py --lanl --status                          # Level 3 progress table
    python scripts/develop.py --lanl --freeze                          # pick the Level 3 predictive model

Test partitions and external targets are never read by this script.
"""
import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))


def start_log(what):
    import datetime as dt
    from src.utils import paths
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    from preprocess import Tee
    stamp = dt.datetime.now(dt.timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    log = paths.RESULTS / "models" / "logs" / f"{stamp}_{what}.log"
    sys.stdout = Tee(log, sys.stdout)
    sys.stderr = Tee(log, sys.stderr)
    print(f"command: {' '.join(sys.argv)}\nlog: {log}")


def status():
    import pandas as pd
    from src.models.develop import summary_table
    from src.utils import paths
    t = pd.DataFrame(summary_table())
    out = paths.RESULTS / "models" / "development" / "summary.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    lines = ["# Model development (validation only)", "", "_Generated by `scripts/develop.py --status`. "
             "Test partitions and external targets are sealed until the freeze (ADR-0007)._", "",
             "| feature space | candidate | complete | grid | seeds | selected | val macro-F1 (mean ± sd) |",
             "|---|---|---|---|---:|---|---|"]
    for r in t.to_dict("records"):
        v = "" if r["val_macro_f1_mean"] is None else f"{r['val_macro_f1_mean']:.4f} ± {r['val_macro_f1_std']:.4f}"
        lines.append(f"| {r['feature_space']} | {r['candidate']} | {'yes' if r['complete'] else 'no'} | "
                     f"{r['grid_done']} | {r['seeds_done']} | {r['selected'] or ''} | {v} |")
    out.write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


def lanl_status():
    from src.models.lanl_develop import summary_table
    from src.utils import paths
    out = paths.RESULTS / "models" / "development" / "lanl_summary.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    lines = ["# Level 3 model development (LANL days 1-13 only)", "", "_Generated by `scripts/develop.py --lanl "
             "--status`. The test period (days 14-58) is sealed until the Level 3 freeze (ADR-0007)._", "",
             "| candidate | complete | grid | seeds | selected | val early-alert rate (mean ± sd) | val PR-AUC |",
             "|---|---|---|---:|---|---|---|"]
    for r in summary_table():
        v = "" if r["val_early_alert_rate_mean"] is None else \
            f"{r['val_early_alert_rate_mean']:.3f} ± {r['val_early_alert_rate_std']:.3f}"
        pa = "" if r["val_pr_auc_mean"] is None else f"{r['val_pr_auc_mean']:.4f}"
        lines.append(f"| {r['candidate']} | {'yes' if r['complete'] else 'no'} | {r['grid_done']} | {r['seeds_done']} | "
                     f"{r['selected'] or ''} | {v} | {pa} |")
    out.write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--space", nargs="+")
    ap.add_argument("--candidate", nargs="+")
    ap.add_argument("--all", action="store_true")
    ap.add_argument("--status", action="store_true")
    ap.add_argument("--freeze", action="store_true")
    ap.add_argument("--lanl", action="store_true", help="Level 3 (LANL) instead of Level 1-2")
    a = ap.parse_args()
    if a.lanl:
        from src.models import lanl_develop as L
        if a.status:
            return lanl_status()
        if a.freeze:
            start_log("freeze_lanl")
            from src.models.seal import freeze_lanl
            freeze_lanl()
            return lanl_status()
        cands = list(L.load_config()["candidates"]) if a.all or not a.candidate else a.candidate
        start_log("lanl_" + "_".join(cands))
        for c in cands:
            L.develop(c)
        return lanl_status()
    from src.models.develop import develop, load_models_config
    cfg = load_models_config()
    if a.status:
        return status()
    if a.freeze:
        start_log("freeze")
        from src.models.seal import freeze
        freeze()
        return status()
    spaces = list(cfg["feature_spaces"]) if a.all or not a.space else a.space
    cands = list(cfg["candidates"]) if a.all or not a.candidate else a.candidate
    unknown = [s for s in spaces if s not in cfg["feature_spaces"]] + [c for c in cands if c not in cfg["candidates"]]
    if unknown or not (a.all or a.candidate):
        ap.error(f"give --candidate from {list(cfg['candidates'])} (and --space from {list(cfg['feature_spaces'])}) "
                 f"or --all (unknown: {unknown})")
    start_log("_".join(spaces + cands) if not a.all else "all")
    for s in spaces:
        for c in cands:
            develop(s, c)
    status()


if __name__ == "__main__":
    main()
