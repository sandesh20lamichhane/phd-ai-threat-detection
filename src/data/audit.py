"""Data cards (docs/data_cards/<id>.md) generated from the preprocessing report, so the numbers in the
thesis come from one place."""
import yaml

from ..utils import paths


def _registry():
    reg = yaml.safe_load((paths.CONFIG / "datasets.yaml").read_text())["datasets"]
    return {d["id"]: d for d in reg}


def _table(d, head=("", "rows")):
    if not d:
        return "_none_\n"
    rows = [f"| {head[0]} | {head[1]} |", "|---|---:|"]
    rows += [f"| {k} | {v:,} |" if isinstance(v, int) else f"| {k} | {v} |"
             for k, v in sorted(d.items(), key=lambda kv: (-kv[1] if isinstance(kv[1], int) else 0, kv[0]))]
    return "\n".join(rows) + "\n"


def _split_table(sp):
    fams = sorted({f for col in sp["family_by_partition"].values() for f in col})
    cols = [c for c in ("train", "val", "test", "external", "purged", "excluded") if c in sp["family_by_partition"]]
    out = ["| family | " + " | ".join(cols) + " |", "|---|" + "---:|" * len(cols)]
    for f in fams:
        out.append(f"| {f} | " + " | ".join(f"{sp['family_by_partition'][c].get(f, 0):,}" for c in cols) + " |")
    return "\n".join(out) + "\n"


def _match(e):
    if "manifest_sha256_match" in e:
        return "yes" if e["manifest_sha256_match"] else "**NO**"
    if "zip_sha256_in_manifest" in e:
        return "member of a zip listed in the manifest" if e["zip_sha256_in_manifest"] else "zip not in manifest"
    return e.get("manifest_note", "not in the manifest")


def render(report, ds):
    reg = _registry().get(report["dataset"], {})
    c, sch = report["counts"], report["schema"]
    lines = [f"# {reg.get('name', report['dataset'])}", "",
             "_Generated by `scripts/preprocess.py` from `results/data_audit/"
             f"{report['dataset']}/report.json`; do not edit by hand._", "",
             f"- **Role:** {report['role']}",
             f"- **Citation:** {(reg.get('cite') or 'see config/datasets.yaml').strip()}",
             f"- **Protocol / output version:** {report['protocol_version']} / {report['output_version']}",
             f"- **Code commit:** `{report['run']['git_commit']}`; config SHA-256 `{report['run'].get('config_sha256')}`",
             f"- **Built:** {report['run']['utc']}" + (f" (pilot, first {report['max_rows']:,} rows only)"
                                                        if report.get("max_rows") else ""),
             "", "## Inputs", "", "| file | bytes | rows | SHA-256 | matches manifest |", "|---|---:|---:|---|---|"]
    for e in report["inputs"]:
        sha = e.get("sha256") or e.get("sha256_of_member") or ""
        lines.append(f"| {e['file']} | {e.get('bytes_read', e['size']):,} | {e.get('rows', 0):,} | `{sha[:16]}…` | "
                     f"{_match(e)} |")
    lines += ["", "## Rows", "",
              f"| step | rows |", "|---|---:|",
              f"| read | {c['rows_read']:,} |",
              f"| all-NaN rows dropped | {c['all_nan_rows_dropped']:,} |",
              f"| exact duplicates removed (features + label) | {c['exact_duplicates_removed']:,} |",
              f"| **retained** | **{c['rows_out']:,}** |",
              f"| of which \"Attempted\" (excluded from primary analysis) | {c['attempted_rows']:,} |",
              f"| \"Attempted\" rows identical to a benign flow | {c['attempted_rows_identical_to_a_benign_flow']:,} |",
              f"| rows in conflicting-label groups (kept, flagged) | {c['conflict_rows']:,} "
              f"({c['conflicting_label_feature_vectors']:,} feature vectors) |",
              f"| rows in conflicting benign/attack groups | {c['binary_conflict_rows']:,} |",
              f"| rows in near-duplicate groups (3 s.f., reported only) | {c['rows_in_near_duplicate_groups']:,} |",
              "", "## Classes", "", "### Canonical family before and after cleaning", ""]
    fi, fo = report["classes"]["family_in"], report["classes"]["family_out"]
    lines += ["| family | in | duplicates removed | out | multiclass task |", "|---|---:|---:|---:|---|"]
    for f in sorted(fi, key=lambda k: -fi[k]):
        mc = report["multiclass_families"].get(f, {}).get("in_multiclass_task", "")
        lines.append(f"| {f} | {fi[f]:,} | {report['classes']['duplicates_removed_by_family'].get(f, 0):,} | "
                     f"{fo.get(f, 0):,} | {mc} |")
    lines += ["", "### Raw label → family", "", "| raw label | family | rows in |", "|---|---|---:|"]
    for raw, fam in sch["label_map"].items():
        lines.append(f"| `{raw}` | {fam} | {report['classes']['raw_in'].get(raw, 0):,} |")
    lines += ["", "## Columns", "", f"**Features ({len(sch['feature_columns'] or [])}):** "
              + ", ".join(f"`{x}`" for x in sch["feature_columns"] or []), "",
              "**Removed from the feature matrix:**", "", "| column | reason |", "|---|---|"]
    lines += [f"| `{k}` | {v} |" for k, v in sch["removed_columns"].items()]
    lines += ["", "**Value problems** (set to NaN; no imputation before the split):", "",
              "- ±inf: " + (", ".join(f"`{k}` {v:,}" for k, v in sch["inf_values_to_nan"].items()) or "none"),
              "- unparseable text: " + (", ".join(f"`{k}` {v:,}" for k, v in sch["unparseable_values_to_nan"].items())
                                       or "none"),
              "- float32 overflow: " + (", ".join(f"`{k}` {v:,}" for k, v in sch["float32_overflow_to_nan"].items())
                                       or "none"),
              f"- timestamps that could not be parsed: {sch['timestamps_unparsed']:,}",
              f"- official binary label disagreeing with the attack category: {sch['binary_label_disagreements']:,}",
              "", "NaN counts per column after cleaning:", "", _table(report["nan_counts_after_cleaning"], ("column", "NaN"))]
    lines += ["## Splits", ""]
    for name, sp in report["splits"].items():
        integ = sp["integrity"]
        lines += [f"### `{name}` ({sp['type']}, seed {sp['seed']}, {sp['block_seconds']} s blocks)", "",
                  _split_table(sp),
                  f"Purged at partition boundaries: {sp['purged_rows']:,}. "
                  f"Split file SHA-256 `{sp['sha256'][:16]}…`.", ""]
        if sp["diagnostics"].get("strata_kept_in_train"):
            lines.append("Strata with fewer than 3 blocks on a day (kept in train): "
                         + "; ".join(f"{d['day']} {d['stratum']} ({d['blocks']})"
                                     for d in sp["diagnostics"]["strata_kept_in_train"]) + "\n")
        for pair, v in integ.get("pairs", {}).items():
            lines.append(f"- {pair}: exact overlap {v['exact_feature_and_label_overlap']}, "
                         f"same features with another label {v['same_features_other_label_share']:.4%}, "
                         f"near-duplicates {v['near_duplicate_share']:.4%}")
        lines.append("")
    lines += ["## Output", "", f"`{report['outputs']['dir']}`: {len(report['outputs']['parquet_sha256'])} parquet "
              "files; SHA-256 values in the report."]
    return "\n".join(lines) + "\n"


def write_data_card(report, ds):
    p = paths.DATA_CARDS / f"{report['dataset']}.md"
    p.write_text(render(report, ds))
    return p
